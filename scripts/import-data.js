// SOIP data import / refresh (Milestone 3). Reads the approved synthetic CSV/JSON files and loads them into Supabase.
// It never modifies or regenerates the source files.
//
//   node scripts/import-data.js                 live import (needs SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY)
//   node scripts/import-data.js --dry-run       transform + validate only, no database access
//   node scripts/import-data.js --emit-sql      also write supabase/seed/synthetic_seed.sql for manual execution
//
// The service-role key is read ONLY from the environment / .env, is server-side only, and is never bundled.

import fs from 'node:fs';
import path from 'node:path';
import { ROOT, buildPayload, getValidatorFindings, ImportDataError } from './lib/transform.js';
import { runImport, ImportError } from './lib/importer.js';

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const dryRun = flag('--dry-run');
const emitSql = flag('--emit-sql');
const reportPath = path.join(ROOT, 'reports', dryRun || emitSql ? 'last-dry-run-report.json' : 'last-import-report.json');

function loadDotEnv() {
  const p = path.join(ROOT, '.env');
  if (!fs.existsSync(p)) return;
  for (const line of fs.readFileSync(p, 'utf8').split('\n')) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !line.trim().startsWith('#') && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
function writeReport(report) {
  fs.mkdirSync(path.dirname(reportPath), { recursive: true });
  fs.writeFileSync(reportPath, JSON.stringify(report, null, 2) + '\n');
  console.log(`Report written to ${path.relative(ROOT, reportPath)}`);
}
const printCounts = (c) => Object.entries(c).forEach(([k, v]) => console.log(`  ${k.padEnd(26)} ${v}`));

async function main() {
  loadDotEnv();
  const validator = getValidatorFindings();
  const { payload, meta, expected, normalization } = buildPayload({ findings: validator.findings, triggeredBy: emitSql ? 'manual-sql' : 'cli' });
  console.log(`Source checksum ${meta.source_checksum.slice(0, 12)}...  Validator: ${validator.summary.findings_intentional} intentional, ${validator.summary.findings_unexpected} unexpected findings.`);
  console.log('Records to import:'); printCounts(expected);

  if (emitSql) {
    const out = path.join(ROOT, 'supabase', 'seed', 'synthetic_seed.sql');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const sql = [
      '-- SOIP synthetic seed (generated by `npm run data:emit-sql`; do not edit by hand).',
      '-- Requires migrations 0001-0003. Run in the Supabase SQL editor (runs as an admin role). Idempotent.',
      `select public.soip_import_all($soip_payload$${JSON.stringify(payload)}$soip_payload$::jsonb, $soip_meta$${JSON.stringify(meta)}$soip_meta$::jsonb);`,
      '',
    ].join('\n');
    fs.writeFileSync(out, sql);
    console.log(`Seed SQL written to ${path.relative(ROOT, out)} (${Math.round(sql.length / 1024)} KB)`);
  }
  if (dryRun || emitSql) {
    writeReport({ status: 'dry-run', expected, normalization, validator_summary: validator.summary, source_checksum: meta.source_checksum, source_files: meta.source_files });
    console.log('Normalization:'); printCounts(normalization);
    console.log('Dry run complete. No database access was made.');
    return;
  }

  const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key || /your-/.test(url + key)) {
    console.error('Supabase credentials not set. Define SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env (see .env.example), or use --dry-run.');
    process.exit(2);
  }
  const { createClient } = await import('@supabase/supabase-js');
  const client = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  const report = await runImport({ client, payload, meta, expected });
  report.normalization = normalization;
  writeReport(report);
  console.log(`Import ${report.status}. Run ${report.run_id}`);
  console.log('Inserted / updated per table:');
  for (const [k, v] of Object.entries(report.row_stats)) if (typeof v === 'object') console.log(`  ${k.padEnd(26)} +${v.inserted} / ~${v.updated}`);
  if (report.mismatches.length) { console.error('Count mismatches:', report.mismatches); process.exit(1); }
}

main().catch((e) => {
  if (e instanceof ImportError) { console.error(`ERROR: ${e.message}`); if (e.hint) console.error(`HINT: ${e.hint}`); }
  else if (e instanceof ImportDataError) console.error(`DATA ERROR: ${e.message}`);
  else console.error(e);
  process.exit(1);
});
